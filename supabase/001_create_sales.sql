-- Run once as the database owner in Supabase SQL Editor.
-- Existing tables are not modified or overwritten; name collisions fail the transaction.
begin;

create table public.sales (
  id bigint generated by default as identity primary key,
  sale_date date not null,
  region text not null check (length(trim(region)) > 0),
  store text not null check (length(trim(store)) > 0),
  product text not null check (length(trim(product)) > 0),
  plan text,
  quantity integer check (quantity >= 0),
  revenue bigint not null check (revenue >= 0),
  staff text,
  created_at timestamptz not null default now()
);
create index sales_sale_date_idx on public.sales (sale_date);

-- Explicit reader allowlist: creating an Auth account alone does not grant sales access.
create table public.dashboard_readers (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.sales enable row level security;
alter table public.dashboard_readers enable row level security;
revoke all on public.sales, public.dashboard_readers from anon, authenticated;
grant usage on schema public to authenticated;
grant select on public.sales, public.dashboard_readers to authenticated;
create policy dashboard_readers_self on public.dashboard_readers
  for select to authenticated using (user_id = (select auth.uid()));
create policy sales_read_by_dashboard_readers on public.sales
  for select to authenticated using (
    exists (select 1 from public.dashboard_readers where user_id = (select auth.uid()))
  );

-- Register this table only; leave all other publication entries unchanged.
do $$
begin
  if not exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    raise exception 'supabase_realtime publication is missing. Enable Supabase Realtime first.';
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'sales'
  ) then
    alter publication supabase_realtime add table public.sales;
  end if;
end $$;
commit;
