const { spawnSync } = require('node:child_process');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname,'..');
const base = {...process.env,SUPABASE_URL:'',SUPABASE_PUBLISHABLE_KEY:'',SUPABASE_ANON_KEY:'',NEXT_PUBLIC_SUPABASE_URL:'',NEXT_PUBLIC_SUPABASE_ANON_KEY:'',NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY:'',SUPABASE_SCHEMA:'public',SUPABASE_TABLE:'sales',SUPABASE_COLUMNS:''};
function build(vars={}) {return spawnSync(process.execPath,['scripts/build.mjs'],{cwd:root,env:{...base,...vars},encoding:'utf8'});}
const url='https://salescope-test.supabase.co';
assert.notEqual(build({SUPABASE_URL:url}).status,0);
assert.notEqual(build({SUPABASE_PUBLISHABLE_KEY:'sb_publishable_test'}).status,0);
assert.notEqual(build({SUPABASE_URL:url,SUPABASE_PUBLISHABLE_KEY:'sb_secret_private_key'}).status,0);
const jwt = role => 'eyJhbGciOiJIUzI1NiJ9.'+Buffer.from(JSON.stringify({role})).toString('base64url')+'.test-signature';
assert.notEqual(build({SUPABASE_URL:url,SUPABASE_ANON_KEY:jwt('service_role')}).status,0);
assert.notEqual(build({SUPABASE_URL:'http://remote.supabase.co',SUPABASE_PUBLISHABLE_KEY:'sb_publishable_test'}).status,0);
assert.notEqual(build({SUPABASE_URL:url,SUPABASE_PUBLISHABLE_KEY:'sb_publishable_test',SUPABASE_TABLE:'sales,*'}).status,0);
assert.notEqual(build({SUPABASE_URL:url,SUPABASE_PUBLISHABLE_KEY:'sb_publishable_test',SUPABASE_COLUMNS:'{"id":"id,secret"}'}).status,0);
let result=build({NEXT_PUBLIC_SUPABASE_URL:url,NEXT_PUBLIC_SUPABASE_ANON_KEY:jwt('anon'),UNRELATED_PRIVATE_KEY:'must-not-appear'});
assert.equal(result.status,0,result.stderr);
let config=fs.readFileSync(path.join(root,'dist/runtime-config.js'),'utf8');
assert.ok(config.includes('"mode":"supabase"'));
assert.ok(!config.includes('must-not-appear'));
assert.ok(!fs.existsSync(path.join(root,'dist/data/sales.js')));
assert.ok(!fs.existsSync(path.join(root,'dist/data/sales-source.xlsx')));
assert.ok(!fs.existsSync(path.join(root,'dist/.env')));
result=build();assert.equal(result.status,0,result.stderr);
config=fs.readFileSync(path.join(root,'dist/runtime-config.js'),'utf8');
assert.ok(config.includes('"mode":"demo"'));
assert.ok(fs.existsSync(path.join(root,'dist/data/sales.js')));
console.log('PASS: complete/partial config, public key aliases, service/secret key rejection, URL and column validation, deployment file isolation, and explicit demo mode.');
